"""Phase 6 — retrieval quality evaluation (document hit@k, provision hit@k, MRR) per language and per mode.

Usage:  python scripts/evaluate_retrieval.py [--json out.json] [--markdown docs/RETRIEVAL_EVAL.md]
Runs against the real local index (frontend/data/rag_index) and the real multilingual embedding model.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.config import BACKEND_DIR, settings  # noqa: E402
from app.legal.embeddings import FastEmbedEmbedder  # noqa: E402
from app.legal.index import LocalIndex  # noqa: E402
from app.legal.retrieval import analyze_query, search_local  # noqa: E402

EVAL_FILE = BACKEND_DIR / "eval" / "retrieval_eval.json"


def evaluate(index: LocalIndex, embedder, mode: str, k: int, queries: list[dict]) -> dict:
    per_lang: dict[str, dict] = defaultdict(lambda: {"n": 0, "doc_hits": 0, "section_hits": 0, "section_n": 0, "rr": 0.0,
                                                    "misses": []})
    for q in queries:
        analysis = analyze_query(q["query"])
        if mode == "lexical":
            analysis_embedder = None
        elif mode == "semantic":
            analysis.lexical_terms = []
            analysis_embedder = embedder
        else:
            analysis_embedder = embedder
        results, _ = search_local(index, analysis, k, analysis_embedder)
        docs = [r.chunk["document_id"] for r in results]
        sections = [r.chunk.get("section_or_article", "") for r in results]
        stats = per_lang[q["language"]]
        stats["n"] += 1
        rank = next((i for i, d in enumerate(docs) if d in q["expected_documents"]), None)
        if rank is not None:
            stats["doc_hits"] += 1
            stats["rr"] += 1 / (rank + 1)
        if q["expected_sections"]:
            stats["section_n"] += 1
            if any(s in q["expected_sections"] for s in sections):
                stats["section_hits"] += 1
            else:
                stats["misses"].append({"query": q["query"], "got": [f"{d} {s}" for d, s in zip(docs, sections)][:3]})
    report = {}
    for lang, s in per_lang.items():
        report[lang] = {
            "queries": s["n"],
            "document_hit_at_k": round(s["doc_hits"] / s["n"], 3),
            "provision_hit_at_k": round(s["section_hits"] / s["section_n"], 3) if s["section_n"] else None,
            "mrr": round(s["rr"] / s["n"], 3),
            "provision_misses": s["misses"],
        }
    return report


def to_markdown(results: dict, k: int, index: LocalIndex) -> str:
    lines = [
        "# Retrieval Evaluation",
        "",
        f"Index: {index.size} chunks, {len({c['document_id'] for c in index.chunks})} official documents, "
        f"embeddings: `{index.embedding_model}` (384-d). k = {k}.",
        "",
        "Generated by `python scripts/evaluate_retrieval.py --markdown docs/RETRIEVAL_EVAL.md`. "
        "Queries: `eval/retrieval_eval.json`. English, Roman Urdu and Urdu are reported separately.",
        "",
        "| Mode | Language | Queries | Document hit@k | Provision hit@k | MRR |",
        "|---|---|---|---|---|---|",
    ]
    for mode, report in results.items():
        for lang in ("english", "roman_urdu", "urdu"):
            r = report.get(lang)
            if r:
                prov = "—" if r["provision_hit_at_k"] is None else f"{r['provision_hit_at_k']:.0%}"
                lines.append(f"| {mode} | {lang} | {r['queries']} | {r['document_hit_at_k']:.0%} | {prov} | {r['mrr']:.2f} |")
    lines += ["", "## Hybrid-mode provision misses", ""]
    for lang, r in results["hybrid"].items():
        for miss in r["provision_misses"]:
            lines.append(f"* **{lang}** — `{miss['query']}` → top: {', '.join(miss['got']) or 'nothing'}")
    if not any(r["provision_misses"] for r in results["hybrid"].values()):
        lines.append("* none")
    lines += [
        "",
        "## Caveats",
        "",
        "* The query set is small (35) and was also used while tuning the Roman-Urdu/Urdu bridge vocabulary and the",
        "  curated terminology hints (FIR → CrPC s.154 etc.), so these numbers are optimistic. Add new, unseen",
        "  queries from real citizen intakes before relying on them.",
        "* All modes share query analysis (bridging, exact section references, terminology hints); `semantic` means",
        "  the lexical BM25 leg is disabled, not that no rules apply.",
        "* Pure multilingual-embedding similarity between Roman Urdu and English legal text is weak (≈0.05 cosine",
        "  for a Roman-Urdu phrase vs. its English equivalent in a spot check); Roman Urdu relies on the bridge.",
        "* The corpus holds 13 federal statutes only. Provincial laws (e.g. Sindh Rented Premises Ordinance) are",
        "  metadata-only until official PDFs are verified, so tenancy questions return metadata pointers or federal law.",
        "* Section labels come from heading detection; chunks far from a heading carry no label (section_confidence",
        "  `low`) rather than a possibly wrong one.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", default="")
    parser.add_argument("--markdown", default="")
    args = parser.parse_args()
    spec = json.loads(EVAL_FILE.read_text(encoding="utf-8"))
    index, status = LocalIndex.load(settings.chunks_path, settings.embeddings_path, settings.embeddings_meta_path)
    if not index.size:
        print("Index is empty — build it first.", file=sys.stderr)
        return 1
    embedder = FastEmbedEmbedder() if index.embeddings is not None else None
    k = spec.get("k", 5)
    results = {mode: evaluate(index, embedder, mode, k, spec["queries"])
               for mode in (("lexical", "semantic", "hybrid") if embedder else ("lexical",))}
    if "hybrid" not in results:
        results["hybrid"] = results["lexical"]
    summary = {mode: {lang: {k2: v for k2, v in r.items() if k2 != "provision_misses"} for lang, r in rep.items()}
               for mode, rep in results.items()}
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
    if args.markdown:
        Path(args.markdown).write_text(to_markdown(results, k, index), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
